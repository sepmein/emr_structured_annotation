from pathlib import Path
import re

base = Path('documentation')
source = (base / '附件症状体征同义词提取.md').read_text(encoding='utf-8')
section = source.split('## A：')[1].split('## B：')[0]
entries = {}
pages = {}
page = None
for line in section.splitlines():
    if line.startswith('### PDF'):
        page = re.search(r'PDF第(\d+)页', line).group(1)
    m = re.match(r'\*\*([^*]+)\*\*(?:（[^）]+）)?：(.+)', line)
    if m:
        name, text = m.groups()
        if name in entries:
            entries[name] = entries[name].rstrip('。') + '、' + text
            pages[name].append(page)
        else:
            entries[name] = text
            pages[name] = [page]

groups = [
    ('一、全身症状与起病特征', '发热 寒战 疲劳 起病急'),
    ('二、呼吸道症状与体征', '咳嗽 咳痰 咽痛 鼻塞 流涕 气短 听诊呼吸音异常 胸痛 咯血 声音嘶哑 发绀'),
    ('三、消化道症状', '恶心 呕吐 腹痛 腹泻 稀便 水样便 粘液便 脓血便 里急后重 呕血 便血 胃肠道出血'),
    ('四、皮肤、黏膜及其他体征', '皮疹 粘膜疹 皮肤出血 黏膜出血 鼻衄 牙龈出血 淋巴结肿大 脾脏肿大'),
    ('五、神经、精神及感觉症状', '头痛 认知障碍 精神行为异常 意识障碍 脑膜刺激征 神经麻痹 嗅觉障碍 味觉障碍 眩晕 晕厥 抽搐 感觉丧失 步态障碍'),
    ('六、关节与肌肉症状', '关节痛 肌肉酸痛 肌肉疼痛 肌群松弛和萎缩'),
    ('七、检查异常与疾病相关词', '白细胞异常 C反应蛋白升高 贫血 血小板下降 急性胃肠炎 过敏性紫癜 药物性紫癜 白血病 再生障碍性贫血 肝硬化'),
]
names = [name for _, items in groups for name in items.split()]
assert len(names) == len(set(names)) == len(entries) == 62
assert set(names) == set(entries)

parts = ['''# 临床症状、体征同义词及相关识别用语汇编

《临床症候群识别规则（征求意见稿）》附件列有62类症状、体征及相关用语。《全国聚集性不明原因肺炎监测方案》附件中的发热同义词与其一致，另列体温、肺炎影像、病原检测及流行病学关联的识别用语。

附件所称“同义词”包括近义表达、相关表现和识别关键词，部分词语并非医学上的等价概念。以下保留附件用词；检查异常和疾病名称另列。发热词条适用于两份文件，其余62类词表中的词条均出自《临床症候群识别规则（征求意见稿）》附件。
''']
for title, items in groups:
    parts.append('## ' + title + '\n')
    for name in items.split():
        parts.append('### ' + name + '\n\n' + entries[name] + '\n')

parts.append('''## 八、肺炎监测相关识别用语

| 项目 | 识别用语或条件 |
| --- | --- |
| 体温 | 基础体温测定、体温监测、体温测量、体温检查、监测体温数字 |
| 肺炎影像 | 肺部炎症、肺炎、肺部阴影 |
| 肺炎诊断 | 诊断编码前三位为J12至J18 |
| 病原检验阳性 | 阳性、弱阳性 |
| 家庭住址关联 | 同住、同生活 |
| 学校或工作单位关联 | 同学习、同工作 |

### 体温数值条件

《临床症候群识别规则（征求意见稿）》发热栏列有体温监测、体温测量、体温检查、监测体温数字，以及以下条件：包含“℃”“摄氏度”“度”或“°”，且之前的数字为“37.3/37.5”；体温+数值≥“37.3/37.5”；T/TMAX+数值≥“37.3/37.5”。原文保留“37.3/37.5”的写法。

《全国聚集性不明原因肺炎监测方案》使用的阈值为≥37.3：带“℃”“摄氏度”“度”或“°”的前置数字≥37.3；体温+数值≥37.3；T/TMAX+数值≥37.3。

### 否定词及否定表达

《临床症候群识别规则（征求意见稿）》：无、没有、否认、未见、未诉、否、不伴、并无、不、非、无明显。

《全国聚集性不明原因肺炎监测方案》发热规则：无发热、未（见、诉）发热、不伴发热、没有发热、否认发热、体温恢复正常、无寒战、未见寒战、否认畏寒、无畏寒。

该方案肺炎影像规则：无、没有、未见、未有。

### 常见病原名称及别名

以下用语出自《全国聚集性不明原因肺炎监测方案》附件。“｜”分隔原表并列字样。
''')
pathogen = source.split('1. 新型冠状病毒')[1].split('## 核对结果')[0].strip()
parts.append('1. 新型冠状病毒' + pathogen + '\n')
parts.append('''## 九、词条说明

同一词语可能出现在多个类别中。寒战、畏寒等同时列入发热词条，反胃同时列入恶心和呕吐，痰中带血同时列入咳嗽和咯血。“体温高”等重复词沿用原表写法。

白细胞异常、C反应蛋白升高、血小板下降属于检查异常，白血病、肝硬化等属于疾病，起病急描述起病特征。各词条下的用语应结合病历上下文理解，不能仅凭关键词认定症状存在或满足病例定义。

部分字样及其所属类别仍需审定，包括鼻塞项下的“呼吸窒畅”、流涕项下的“鼻沸、鼻沈”、起病急项下的“骤疾”、淋巴结肿大项下的“淋巴结性”、咳嗽项下的“咕咳、嗽咳”，以及气短项下的“呼吸浅”。这些用语保留扫描原文字样。

## 来源

1. 国家疾控局监测预警司关于征求《临床症候群识别规则（征求意见稿）》意见的函，附件“症状、体征关键词参考表”，PDF第6至13页，附件印刷页码2至9。
2. 关于印发《全国聚集性不明原因肺炎监测方案》的通知（国疾控综监测发〔2026〕22号），附件“聚集性肺炎风险识别规则”，PDF第10至12页。
''')
output = '\n'.join(parts)
for name, text in entries.items():
    assert '### ' + name + '\n\n' + text in output
target = base / '临床症状体征同义词汇编.md'
target.write_text(output, encoding='utf-8')
print(f'已生成结果文档；校验62类词条全部保留，跨页咽痛合并为一项。文件：{target}')
